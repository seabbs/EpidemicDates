# Render the EpidemicDates.jl docstrings to Markdown for the MkDocs site.
#
# Run from the repository root:
#   julia --project=julia docs/julia/make_reference.jl
#
# It writes docs/julia/reference.md, which is gitignored. Docstrings are
# read with Base.Docs, so no packages beyond EpidemicDates are needed.
# Julia docstring syntax is converted for MkDocs Material: signatures and
# doctests become fenced code, ``x`` and ```math blocks become arithmatex
# maths, and [`f`](@ref) becomes a link to the entry on the page.

using EpidemicDates

const MOD = EpidemicDates
const REPO = "https://github.com/seabbs/EpidemicDates"
const OUT = joinpath(@__DIR__, "reference.md")

const EXPORTED = [:delay_pmf, :impute_linelist, :correct_truncation, :weekly]
const INTERNAL = [
    :em_fit, :backsampling_allocate, :mean_shift_allocate, :round_half_up,
    :DMAX,
]

# Raw docstrings, with the file and line each was defined at.
function docstrings(sym::Symbol)
    binding = Base.Docs.Binding(MOD, sym)
    multi = Base.Docs.meta(MOD)[binding]
    return [(join(d.text), d.data) for d in values(multi.docs)]
end

anchor(sym) = replace(string(sym), "!" => "")

function source_link(data)
    path = get(data, :path, nothing)
    path === nothing && return ""
    rel = relpath(path, joinpath(pkgdir(MOD), ".."))
    return "[source]($REPO/blob/main/$rel#L$(data[:linenumber]))"
end

function convert_docstring(text::AbstractString)
    lines = split(chomp(text), '\n')
    out = String[]
    # Leading indented lines are the signature.
    sig = String[]
    while !isempty(lines) && startswith(lines[1], "    ")
        push!(sig, lines[1][5:end])
        popfirst!(lines)
    end
    if !isempty(sig)
        append!(out, ["```julia", sig..., "```"])
    end
    in_math = false
    in_code = false
    for line in lines
        s = String(line)
        if !in_code && s == "```math"
            in_math = true
            push!(out, "\$\$")
        elseif in_math && s == "```"
            in_math = false
            push!(out, "\$\$")
        elseif in_math
            push!(out, s)
        elseif startswith(s, "```")
            in_code = !in_code
            push!(out, startswith(s, "```jldoctest") ? "```julia-repl" : s)
        elseif in_code
            push!(out, s)
        else
            s = replace(s, r"``([^`]+)``" => s"$\1$")
            s = replace(
                s,
                r"\[`([^`]+)`\]\(@ref\)" => function (m)
                    name = match(r"`([^`]+)`", m).captures[1]
                    return "[`$name`](#$(anchor(split(name, '.')[end])))"
                end
            )
            # Docstring section headings become bold labels, with a
            # blank line so Python-Markdown starts a list after them.
            heading = match(r"^# (.+)$", s)
            if heading === nothing
                push!(out, s)
            else
                append!(out, ["**" * heading.captures[1] * "**", ""])
            end
        end
    end
    return join(out, '\n')
end

function entry(io, sym::Symbol; qualified = false)
    name = qualified ? "EpidemicDates.$sym" : string(sym)
    level = qualified ? "###" : "##"
    println(io, level, " `", name, "` { #", anchor(sym), " }")
    println(io)
    for (text, data) in docstrings(sym)
        println(io, convert_docstring(text))
        println(io)
        link = source_link(data)
        isempty(link) || (println(io, link); println(io))
    end
    return
end

function main()
    open(OUT, "w") do io
        println(
            io, "<!-- Generated by docs/julia/make_reference.jl. ",
            "Do not edit by hand. -->"
        )
        println(io)
        println(io, "# Julia API reference")
        println(io)
        println(
            io, "The public API of `EpidemicDates.jl`, ",
            "generated from its docstrings."
        )
        println(io, "For a guided tour see the [Julia guide](index.md).")
        println(
            io, "For the Python equivalent see the ",
            "[Python API reference](../python/reference.md)."
        )
        println(io)
        println(io, "## Package")
        println(io)
        println(io, convert_docstring(first(docstrings(:EpidemicDates))[1]))
        println(io)
        for sym in EXPORTED
            entry(io, sym)
        end
        println(io, "## Internal building blocks")
        println(io)
        println(io, "These are not exported and may change.")
        println(
            io, "Call them with the module prefix, for example ",
            "`EpidemicDates.em_fit`."
        )
        println(io)
        for sym in INTERNAL
            entry(io, sym; qualified = true)
        end
    end
    return OUT
end

println("Wrote ", main())
