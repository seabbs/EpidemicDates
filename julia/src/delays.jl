"""
Default maximum onset-to-report delay in days.
Delay pmfs cover delays `0:DMAX`.
"""
const DMAX = 60

# Gamma CDF with shape k and scale θ, zero for x <= 0.
function _gamma_cdf(x::Float64, k::Float64, θ::Float64)
    x <= 0 && return 0.0
    return first(gamma_inc(k, x / θ))
end

# Integrated Gamma CDF, G(x) = x F(x; k, θ) - k θ F(x; k + 1, θ).
function _integrated_cdf(x::Float64, k::Float64, θ::Float64)
    x <= 0 && return 0.0
    return x * _gamma_cdf(x, k, θ) - k * θ * _gamma_cdf(x, k + 1, θ)
end

function _check_positive(x::Real, what::String)
    (isfinite(x) && x > 0) ||
        throw(ArgumentError("$what must be a positive finite number, got $x"))
    return nothing
end

@doc raw"""
    delay_pmf(mean, sd; dmax = 60)

Double interval censored daily Gamma delay pmf on delays `0:dmax`.

The primary event (onset) is uniform within its day and the secondary
event (report) is censored to its day, as in primarycensored.
The probability of a delay of ``d`` days is

```math
P(d) = G(d + 1) - 2 G(d) + G(d - 1),
```

```math
G(x) = \int_0^x F(u; k, \theta) \, du
= x F(x; k, \theta) - k \theta F(x; k + 1, \theta),
```

where ``F(x; k, \theta)`` is the Gamma CDF with shape
``k = (\mu / \sigma)^2`` and scale ``\theta = \sigma^2 / \mu``, and
``G(x) = 0`` for ``x \le 0``.
Negative values from rounding are set to 0.
The pmf is truncated at `dmax` and renormalised.

# Arguments
- `mean`: mean ``\mu`` of the continuous Gamma delay, in days.
  Must be positive and finite.
- `sd`: standard deviation ``\sigma`` of the continuous Gamma delay, in
  days. Must be positive and finite.
- `dmax`: maximum delay. Must be non-negative.

# Returns
A `Vector{Float64}` of length `dmax + 1` that sums to 1.
Element `d + 1` is the probability of a delay of `d` days.

# Throws
`ArgumentError` if `mean` or `sd` is not positive and finite, or if
`dmax` is negative.

# Examples
```jldoctest
julia> pmf = delay_pmf(8, 8);

julia> length(pmf)
61

julia> round(sum(pmf); digits = 12)
1.0

julia> round.(pmf[1:3]; digits = 4)
3-element Vector{Float64}:
 0.06
 0.1105
 0.0975
```

!!! warning
    This code was generated by an LLM.
    Sam Abbott has only checked the interactive page, not this package.
    Treat the results as exploratory.
"""
function delay_pmf(mean::Real, sd::Real; dmax::Integer = DMAX)
    _check_positive(mean, "mean")
    _check_positive(sd, "sd")
    dmax >= 0 || throw(ArgumentError("dmax must be non-negative, got $dmax"))
    μ, σ = Float64(mean), Float64(sd)
    k = (μ / σ)^2
    θ = σ^2 / μ
    pmf = map(0:dmax) do d
        g = _integrated_cdf(d + 1.0, k, θ) -
            2 * _integrated_cdf(d + 0.0, k, θ) +
            _integrated_cdf(d - 1.0, k, θ)
        return max(g, 0.0)
    end
    return pmf ./ sum(pmf)
end
