@doc raw"""
    correct_truncation(counts, delay, cutoff; min_cover = 0.05)

Correct daily onset counts for right truncation at the cut-off.

The data are cut at day ``T`` = `cutoff`, so onsets on day ``s`` count
only cases reported by ``T``.
Each day is divided by the expected fraction of its cases reported by
then,

```math
F(T - s) = \sum_{d \le T - s} f(d),
\qquad
\hat C(s) = \frac{\hat n(s)}{F(T - s)},
```

where ``f`` is the forward delay pmf `delay` on delays `0, 1, ...`.
Days with ``F(T - s)`` below `min_cover`, including days after ``T``,
are set to 0.
The correction assumes the imputed curve has the right shape and is only
incomplete.
It cannot rescue cases placed on the wrong day.
In real data the delay would itself have to be estimated.

# Arguments
- `counts`: daily onset counts, element `i` is onset day `i - 1`.
- `delay`: forward delay pmf, element `d + 1` is a delay of `d` days.
  It is normalised before use.
- `cutoff`: data cut-off day ``T``. Must be non-negative.
- `min_cover`: smallest fraction reported that is corrected.

# Returns
A `Vector{Float64}` the same length as `counts`.

# Throws
`ArgumentError` if `cutoff` is negative, `min_cover` is not in
``(0, 1]``, or `delay` is not a valid pmf.

# Examples
```jldoctest
julia> correct_truncation([10.0, 10.0, 10.0], [0.5, 0.5], 2)
3-element Vector{Float64}:
 10.0
 10.0
 20.0
```

!!! warning
    This code was generated by an LLM.
    Sam Abbott has only checked the interactive page, not this package.
    Treat the results as exploratory.
"""
function correct_truncation(counts::AbstractVector{<:Real},
        delay::AbstractVector{<:Real}, cutoff::Integer;
        min_cover::Real = 0.05)
    cutoff >= 0 ||
        throw(ArgumentError("cutoff must be non-negative, got $cutoff"))
    0 < min_cover <= 1 ||
        throw(ArgumentError("min_cover must be in (0, 1], got $min_cover"))
    pmf = _check_delay(delay)
    cdf = cumsum(pmf)
    return map(enumerate(counts)) do (i, n)
        days_left = cutoff - (i - 1)
        cover = days_left < 0 ? 0.0 : cdf[min(days_left, length(cdf) - 1) + 1]
        return cover >= min_cover ? n / cover : 0.0
    end
end

"""
    weekly(daily)

Sum daily counts into weeks.

Week 1 is days 0 to 6 (elements 1 to 7), week 2 is days 7 to 13, and so
on.
A final partial week is kept, so check it before use.

# Returns
A `Vector{Float64}` of length `cld(length(daily), 7)`.

# Examples
```jldoctest
julia> weekly(1:10)
2-element Vector{Float64}:
 28.0
 27.0
```

!!! warning
    This code was generated by an LLM.
    Sam Abbott has only checked the interactive page, not this package.
    Treat the results as exploratory.
"""
function weekly(daily::AbstractVector{<:Real})
    n_weeks = cld(length(daily), 7)
    out = zeros(n_weeks)
    for (i, x) in enumerate(daily)
        out[fld(i - 1, 7) + 1] += x
    end
    return out
end
