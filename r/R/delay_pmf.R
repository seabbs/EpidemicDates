#' Double interval censored daily Gamma delay pmf
#'
#' Computes the pmf of a daily delay whose continuous form is Gamma.
#' The primary event (onset) is uniform within its day.
#' The secondary event (report) is censored to its day.
#' This is the primarycensored form.
#'
#' The pmf is
#' \deqn{P(d) = G(d + 1) - 2 G(d) + G(d - 1),}
#' with
#' \deqn{G(x) = \int_0^x F(u; k, \theta) \, du
#'   = x F(x; k, \theta) - k \theta F(x; k + 1, \theta),}
#' where \eqn{F(x; k, \theta)} is the Gamma CDF with shape
#' \eqn{k = (\mu / \sigma)^2} and scale \eqn{\theta = \sigma^2 / \mu}, and
#' \eqn{G(x) = 0} for \eqn{x \le 0}.
#' The pmf is truncated at `dmax` and renormalised.
#'
#' This matches `gamma_pmf()` in the Python package `epidemic_dates`.
#'
#' @section Warning:
#' This code was generated by an LLM.
#' Sam Abbott has only checked the interactive page.
#'
#' @param mean Mean \eqn{\mu} of the continuous Gamma delay, in days.
#'   Must be positive.
#' @param sd Standard deviation \eqn{\sigma} of the continuous Gamma delay,
#'   in days.
#'   Must be positive.
#' @param dmax Maximum delay \eqn{D}, a non-negative whole number.
#'   Defaults to 60.
#'
#' @return A numeric vector of length `dmax + 1`.
#'   Element `d + 1` is the probability of a delay of `d` days.
#'   It sums to 1.
#'
#' @family delays
#' @export
#'
#' @examples
#' pmf <- delay_pmf(8, 8)
#' length(pmf)
#' sum(pmf)
#' # mean of the censored delay
#' sum(0:60 * pmf)
#' round(delay_pmf(4, 2, dmax = 10), 3)
delay_pmf <- function(mean, sd, dmax = 60) {
  .check_positive(mean, "mean")
  .check_positive(sd, "sd")
  dmax <- .check_scalar_whole(dmax, "dmax", min = 0)
  shape <- (mean / sd)^2
  scale <- sd^2 / mean
  integrated_cdf <- function(x) {
    x <- pmax(x, 0)
    x *
      stats::pgamma(x, shape, scale = scale) -
      shape * scale * stats::pgamma(x, shape + 1, scale = scale)
  }
  days <- seq(0, dmax)
  pmf <- pmax(
    integrated_cdf(days + 1) -
      2 * integrated_cdf(days) +
      integrated_cdf(days - 1),
    0
  )
  pmf / sum(pmf)
}
