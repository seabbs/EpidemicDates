#' Impute missing onsets in a line list
#'
#' Takes one onset day and one report day per case and imputes the missing
#' onsets by each method.
#' Cases with a known onset keep it.
#' Outputs are expected allocations, not random draws.
#'
#' Let \eqn{T} be `cutoff`, \eqn{D} be `max_delay` and \eqn{g(d)} the
#' pooled empirical delay pmf of complete cases.
#' A case with a missing onset reported on day \eqn{t} is placed on onset
#' day \eqn{s} as follows.
#'
#' - `backsampling` spreads it over \eqn{s = t - d} with weight
#'   \eqn{g(d)}, so \eqn{P(s \mid t) = g(t - s)}.
#'   This is the expected allocation of drawing a delay from the pooled
#'   empirical delays.
#' - `mean` moves it back by the mean empirical delay, rounded with halves
#'   up (as JavaScript's `Math.round`):
#'   \deqn{s = t - \lfloor \textstyle\sum_d d \, g(d) + 0.5 \rfloor.}
#' - `fwd` uses the given forward delay \eqn{f}, so
#'   \eqn{P(s \mid t) = f(t - s)}.
#'   It is only returned when `delay` is given.
#'   For a delay matrix, \eqn{P(s \mid t) \propto f_s(t - s)} over onset
#'   days \eqn{0, \dots, t}.
#' - `em` is EM back-projection.
#'   The E-step allocates missing cases by
#'   \eqn{P(s \mid t) \propto \lambda(s) f_{k(s)}(t - s)}, where
#'   \eqn{k(s)} is the period of onset day \eqn{s}.
#'   The M-step alternates three times between
#'   \deqn{\lambda(s) = \frac{n(s)}{F_{k(s)}\big(\min(T - s, D)\big)},
#'     \qquad
#'     f(d) \propto \frac{n(d)}{\sum_{s \le T - d} \lambda(s)},}
#'   where \eqn{n} counts complete and allocated cases by onset day or by
#'   delay and \eqn{F_k} is the CDF of \eqn{f_k}.
#'   By default there is one period and the delay \eqn{f_0 = f} is static,
#'   estimated jointly with \eqn{\lambda} from all cases, allowing for
#'   right truncation.
#'   With `delay_period`, onset days are split into periods of that many
#'   days counted back from the cut-off, and in order
#'   \deqn{f_k(d) \propto \frac{N_k(d) + \kappa h_k(d)}{E_k(d) + \kappa},}
#'   where \eqn{N_k(d)} counts cases with onset in period \eqn{k} and
#'   delay \eqn{d}, \eqn{E_k(d)} sums \eqn{\lambda(s)} over days of
#'   period \eqn{k} up to \eqn{T - d}, \eqn{\kappa} is
#'   `delay_shrinkage`, \eqn{h_0 = f} and \eqn{h_k = f_{k-1}}.
#'   Each period is shrunk towards the one before, with a weight on its
#'   own data that grows with its expected number of cases.
#'   If `delay` is given, `em` holds it fixed (a plug-in) and only
#'   estimates \eqn{\lambda}.
#'   No convergence check is made.
#'
#' All methods assume onsets are missing at random given the report day.
#' If missingness depends on the delay, all are biased.
#'
#' Cases reported before day 0 or after `cutoff` are dropped.
#' Complete cases with a negative onset, an onset after report or a delay
#' over `max_delay` are dropped.
#' They are not imputed.
#' For `backsampling`, `mean` and `fwd`, imputed onsets before day 0 are not
#' in `imputed`.
#' The amount is in `imputed_before_day0`.
#'
#' @section Warning:
#' This code was generated by an LLM.
#' Sam Abbott has only checked the interactive page.
#'
#' @param onset Onset day per case, `NA` where missing.
#'   Either whole numbers of days or a `Date` vector.
#' @param report Report day per case, with no missing values.
#'   Either whole numbers of days (for example days since the first
#'   report) or a `Date` vector.
#'   If either `onset` or `report` is a `Date`, both are converted to days
#'   since the earliest date in either.
#' @param cutoff Data cut-off day \eqn{T}, a non-negative whole number or,
#'   for `Date` input, a `Date`.
#'   Defaults to the last report day.
#' @param delay Optional forward delay pmf.
#'   Element `d + 1` is the probability of a delay of `d` days, for example
#'   from [delay_pmf()].
#'   It is normalised to sum to 1.
#'   Alternatively a matrix with one such pmf per onset day
#'   `0..cutoff` in its rows, for a delay that changes over time.
#'   A given delay is used as is (a plug-in) by `fwd` and held fixed by
#'   `em`.
#'   If given, `imputed` also holds `fwd`.
#'   Cannot be combined with `delay_period`.
#' @param max_delay Longest delay \eqn{D} kept, a non-negative whole number.
#'   Defaults to 60.
#' @param n_iter Number of EM iterations, at least 1.
#'   Defaults to 150.
#' @param delay_period Length in days of the periods of onset days that
#'   get their own EM delay, counted back from the cut-off.
#'   Defaults to `NULL`, one static delay.
#' @param delay_shrinkage Strength, in expected cases, of the shrinkage of
#'   each period's delay towards the previous period's delay.
#'   Must be positive.
#'   Defaults to 10.
#'
#' @return A list.
#'   Daily vectors have length `cutoff + 1` and element `i` is onset day
#'   `i - 1`.
#'   Delay pmfs have length `max_delay + 1` and element `d + 1` is a delay
#'   of `d` days.
#'   - `complete`: onset counts of cases with a known onset.
#'   - `missing_by_report`: counts of missing-onset cases by report day.
#'   - `empirical_delay`: pooled delay pmf of complete cases.
#'   - `imputed`: a list of daily onset counts (complete plus imputed) for
#'     `backsampling`, `mean` and `em`, and `fwd` if `delay` is given.
#'   - `em_delay`: the delay pmf used by EM: the static estimate, the
#'     pooled estimate with `delay_period`, or the given `delay` (its
#'     onset-weighted mean for a matrix).
#'   - `em_delay_by_period`: a matrix with the delay pmf of each period in
#'     its rows. One row without `delay_period`, and one row per onset day
#'     for a delay matrix.
#'   - `delay_period_start`: the first onset day of each period.
#'   - `dropped`: number of cases dropped.
#'   - `imputed_before_day0`: a list with the expected number of
#'     missing-onset cases that `backsampling`, `mean` and (if `delay` is
#'     given) `fwd` place before day 0.
#'   - `cutoff`: the cut-off used, in days.
#'   - `origin`: the `Date` of day 0 for `Date` input, otherwise `NULL`.
#'
#' @family linelist
#' @export
#'
#' @examples
#' onset <- c(0, 2, NA, 5, NA)
#' report <- c(3, 6, 7, 9, 12)
#' res <- impute_linelist(onset, report, cutoff = 12)
#' round(res$imputed$backsampling, 2)
#' res$imputed$mean
#' round(res$imputed$em, 2)
#'
#' # Date input, with a forward delay
#' onset_date <- as.Date(c("2026-05-01", "2026-05-03", NA, "2026-05-06", NA))
#' report_date <- as.Date("2026-05-01") + report + 1
#' res <- impute_linelist(onset_date, report_date, delay = delay_pmf(4, 3))
#' res$origin
#' round(res$imputed$fwd, 2)
#'
#' # a delay estimated for each 4-day period of onsets
#' res <- impute_linelist(onset, report, cutoff = 12, delay_period = 4)
#' res$delay_period_start
#' round(res$em_delay_by_period[, 1:6], 2)
impute_linelist <- function(
  onset,
  report,
  cutoff = NULL,
  delay = NULL,
  max_delay = 60,
  n_iter = 150,
  delay_period = NULL,
  delay_shrinkage = 10
) {
  days <- .linelist_days(onset, report, cutoff)
  onset <- days$onset
  report <- days$report
  cutoff <- days$cutoff
  max_delay <- .check_scalar_whole(max_delay, "max_delay", min = 0)
  n_iter <- .check_scalar_whole(n_iter, "n_iter", min = 1)
  if (!is.null(delay) && !is.null(delay_period)) {
    stop("give either delay or delay_period, not both", call. = FALSE)
  }
  if (!is.null(delay) && !is.matrix(delay)) {
    delay <- .check_pmf(delay, "delay")
  }
  .check_positive(delay_shrinkage, "delay_shrinkage")
  if (length(onset) != length(report)) {
    stop(
      "onset and report must have the same length, got ",
      length(onset),
      " and ",
      length(report),
      call. = FALSE
    )
  }
  if (length(report) == 0L) {
    stop("the line list is empty", call. = FALSE)
  }
  bad_report <- !is.finite(report)
  if (any(bad_report)) {
    stop(
      "report day is missing or infinite for ",
      sum(bad_report),
      " case(s); every case needs a report day",
      call. = FALSE
    )
  }
  if (any(is.infinite(onset))) {
    stop("onset days must not be infinite; use NA if missing", call. = FALSE)
  }
  if (!all(.is_whole(report))) {
    stop("report days must be whole numbers of days", call. = FALSE)
  }
  if (!all(.is_whole(onset[!is.na(onset)]))) {
    stop("onset days must be whole numbers of days", call. = FALSE)
  }
  if (is.null(cutoff)) {
    cutoff <- max(report)
  }
  cutoff <- .check_scalar_whole(cutoff, "cutoff", min = 0)
  period <- .delay_periods(cutoff, delay_period)
  fixed <- NULL
  if (!is.null(delay)) {
    fixed <- .as_delay_matrix(delay, cutoff, max_delay)
    if (is.matrix(delay)) period <- seq(0L, cutoff)
  }

  keep <- report >= 0 & report <= cutoff
  onset <- onset[keep]
  report <- as.integer(report[keep])
  missing <- is.na(onset)
  onset_c <- as.integer(onset[!missing])
  delay_c <- report[!missing] - onset_c
  ok <- onset_c >= 0L & delay_c >= 0L & delay_c <= max_delay
  onset_c <- onset_c[ok]
  delay_c <- delay_c[ok]
  if (length(onset_c) == 0L) {
    stop(
      "no complete cases (cases with both an onset and a report day ",
      "in range) are left, so the delay cannot be estimated",
      call. = FALSE
    )
  }
  report_m <- report[missing]
  n_days <- cutoff + 1L
  complete <- as.numeric(tabulate(onset_c + 1L, n_days))
  missing_by_report <- as.numeric(tabulate(report_m + 1L, n_days))
  empirical <- tabulate(delay_c + 1L, max_delay + 1L)
  empirical <- empirical / sum(empirical)

  n_missing <- sum(missing_by_report)
  backsampling <- .backsampling_allocate(missing_by_report, empirical)
  shift <- .round_half_up(sum(seq(0, max_delay) * empirical))
  mean_shift <- .mean_shift_allocate(missing_by_report, shift)
  fit <- .em_fit(
    onset_c,
    delay_c,
    report_m,
    cutoff,
    max_delay,
    n_iter,
    fixed = fixed,
    period = period,
    shrinkage = delay_shrinkage
  )
  imputed <- list(
    backsampling = complete + backsampling,
    mean = complete + mean_shift,
    em = complete + fit$allocation
  )
  before_day0 <- list(
    backsampling = max(n_missing - sum(backsampling), 0),
    mean = n_missing - sum(mean_shift)
  )
  if (!is.null(delay)) {
    fwd <- if (is.matrix(delay)) {
      .posterior_allocate(missing_by_report, rep(1, n_days), fixed)
    } else {
      .backsampling_allocate(missing_by_report, delay)
    }
    imputed$fwd <- complete + fwd
    before_day0$fwd <- max(n_missing - sum(fwd), 0)
  }
  list(
    complete = complete,
    missing_by_report = missing_by_report,
    empirical_delay = empirical,
    imputed = imputed,
    em_delay = fit$delay,
    em_delay_by_period = fit$delay_by_period,
    delay_period_start = fit$period_start,
    dropped = sum(!keep) + sum(!ok),
    imputed_before_day0 = before_day0,
    cutoff = cutoff,
    origin = days$origin
  )
}

# Convert Date input to whole days since the earliest date. Numeric input is
# returned as numeric with origin NULL.
.linelist_days <- function(onset, report, cutoff) {
  is_date <- c(inherits(onset, "Date"), inherits(report, "Date"))
  if (!any(is_date)) {
    if (!is.null(cutoff) && inherits(cutoff, "Date")) {
      stop("cutoff can only be a Date when report is a Date", call. = FALSE)
    }
    .check_numeric_days(onset, "onset")
    .check_numeric_days(report, "report")
    return(list(
      onset = as.numeric(onset),
      report = as.numeric(report),
      cutoff = cutoff,
      origin = NULL
    ))
  }
  all_na_onset <- !is_date[1] && is.logical(onset) && all(is.na(onset))
  if (!all(is_date) && !all_na_onset) {
    stop(
      "onset and report must both be Date vectors, or both be numeric days",
      call. = FALSE
    )
  }
  onset <- as.Date(onset)
  if (all(is.na(c(onset, report)))) {
    stop("report day is missing for every case", call. = FALSE)
  }
  origin <- min(c(onset, report), na.rm = TRUE)
  if (!is.null(cutoff)) {
    if (!inherits(cutoff, "Date")) {
      stop("cutoff must be a Date when report is a Date", call. = FALSE)
    }
    cutoff <- as.numeric(cutoff - origin)
  }
  list(
    onset = as.numeric(onset - origin),
    report = as.numeric(report - origin),
    cutoff = cutoff,
    origin = origin
  )
}

.check_numeric_days <- function(x, what) {
  if (!(is.numeric(x) || (is.logical(x) && all(is.na(x))))) {
    stop(what, " must be numeric days or a Date vector", call. = FALSE)
  }
  invisible(x)
}
